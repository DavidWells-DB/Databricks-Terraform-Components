#!/usr/bin/env bash
# validate-component.sh <component-dir> — validate one component as an isolated root.
#
# Components declare configuration_aliases and carry no provider blocks. Copy the
# component to a temp dir, add concrete provider configurations for only the aliases
# it declares, then init + validate there. Root-module inputs may remain unset during
# validate, so no synthetic module call or placeholder variable values are needed.
# No credentials are required and nothing is applied.
#
# Used by CI (unit-tests.yml) and usable locally: scripts/validate-component.sh networking/aws/basic

set -euo pipefail
COMPONENT="${1:?usage: validate-component.sh <component-dir>}"
COMPONENT="$(cd "${COMPONENT}" && pwd)"
WRAP="$(mktemp -d /tmp/component-validate.XXXXXX)"
ROOT="${WRAP}/component"

cp -R "${COMPONENT}" "${ROOT}"

PROVIDER_BLOCKS=""
for p in $(grep -oE '^    [a-z0-9]+ = \{' "${COMPONENT}/versions.tf" | tr -d ' ={'); do
  case "${p}" in
    aws) PROVIDER_BLOCKS="${PROVIDER_BLOCKS}
provider \"aws\" { region = \"us-east-1\" }" ;;
    azurerm) PROVIDER_BLOCKS="${PROVIDER_BLOCKS}
provider \"azurerm\" {
  features {}
}" ;;
    google) PROVIDER_BLOCKS="${PROVIDER_BLOCKS}
provider \"google\" {
  project = \"wrapper-validate\"
  region  = \"us-central1\"
}" ;;
    azapi) PROVIDER_BLOCKS="${PROVIDER_BLOCKS}
provider \"azapi\" {}" ;;
    databricks)
      if grep -q 'configuration_aliases.*databricks\.account' "${COMPONENT}/versions.tf"; then
        PROVIDER_BLOCKS="${PROVIDER_BLOCKS}
provider \"databricks\" {
  alias      = \"account\"
  host       = \"https://accounts.cloud.databricks.com\"
  account_id = \"00000000-0000-0000-0000-000000000000\"
}"
      fi
      if grep -q 'configuration_aliases.*databricks\.workspace' "${COMPONENT}/versions.tf"; then
        PROVIDER_BLOCKS="${PROVIDER_BLOCKS}
provider \"databricks\" {
  alias        = \"workspace\"
  host         = \"https://adb-0000000000000000.0.azuredatabricks.net\"
  workspace_id = \"000000000000000\"
}"
      fi
      ;;
    time) : ;; # no config arguments
    *)
      echo "no validation stub defined for provider ${p}" >&2
      exit 2
      ;;
  esac
done

cat > "${ROOT}/validation-providers.tf" <<EOF
# Generated by validate-component.sh; never present in the source component.
${PROVIDER_BLOCKS}
EOF

cd "${ROOT}"
if ! terraform init -backend=false -input=false; then
  echo "INIT FAILED: ${COMPONENT}" >&2
  echo "(validation root kept at ${ROOT} for debugging)" >&2
  exit 1
fi

if terraform validate; then
  echo "VALID: ${COMPONENT}"
  rm -rf "${WRAP}"
else
  echo "INVALID: ${COMPONENT}" >&2
  echo "(validation root kept at ${ROOT} for debugging)" >&2
  exit 1
fi
